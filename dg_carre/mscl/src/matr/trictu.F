      subroutine trictu(a,m,n)
c
c  version : 24.05.91 18:45
c
c====================================================
c*** in situ matrix transposing
c***  input :  a(m,n)
c*** output :  a(n,m)
c====================================================
      dimension a(*)
      logical b
      data    g , e  / 8.e37 , 0.25 /
c====================================================
c
      l=m*n
      if(l.le.1) return
c=====================================================
      s=0.
      b=.false.
      call minmax(a,l,ym,yx)
      if(ym.gt.0.) go to 20
c----------------------------------------------------
      if(abs(ym).lt.g .and. abs(yx).lt.g) go to 10
c----------------------------------------------------
      b=.true.
      call vscale(a,e,a,l)
      ym=ym*e
 10   s=1.-2.*ym
      call vbias(a,s,a,l)
 20   do 100 k=1,l
      x=a(k)
      if(x.lt.0.) go to 100
c----------------------------------------------------
      i=k
 30   j=mod(i-1,n)+1
      j=(i-j)/n+(j-1)*m+1
      if(j.eq.k) go to 40
c----------------------------------------------------
      a(i)=-a(j)
      i=j
      go to 30
c----------------------------------------------------
 40   a(i)=-x
 100  continue
c----------------------------------------------------
      call vscale(a,-1.,a,l)
      call vbias(a,-s,a,l)
      if(b) call vscale(a,1./e,a,l)
c====================================================
      end
