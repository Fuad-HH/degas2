      function expinv(al,n)
c
c  version : 04.02.92 10:23
c
c=====================================================
c*** integral between zero and infinity of the function:
c***
c***               x**n*exp(-x**2-al/x)
c***
c***             al > 0, n = -1 through 3
c***
c***            (a.s.kukushkin, summer 1977)
c***
c*** approximation accurate to 3 decimal digits
c*** needs a function to compute the integral exponent;
c*** the present version relies on nag s13aae
c=====================================================
c
      dimension em(5),bm(5),cm(8),xm(8)
      logical l
      data bm/1.,-1.,0.5,-0.166667,0.0416667/
      data spi,l/1.7725,.false./
      data xm/0.9894,0.944575,0.865631,0.755404,
     1        0.617876,0.458017,0.281604,0.095013/
      data cm/0.027152,0.062254,0.095159,0.124629,
     2        0.149596,0.169157,0.182603,0.189451/
c=====================================================
      ff(x)=x**n*exp(-x*x-a/x)
      xx(x)=dd+x*d
      ef(x)=(ex-al*x)/f
c=====================================================
c
      l=al.le.1.
      a=1.
      if(.not.l) a=al
      ex=exp(-al)
      e2=s13aae(al,ifl)
      f=1.
      n1=n+1
      do 101 i=1,n1
          e2=ef(e2)
  101 f=f+1.
      em(1)=e2
      do 103 i=2,5
          do 102 j=1,2
              e2=ef(e2)
  102     f=f+1.
  103 em(i)=e2
      expinv=0.
      do 104 i=1,5
  104 expinv=expinv+em(i)*bm(i)
c
      pp=0.
      qq=0.
      rr=0.
      m=3-n
      aa=1.
      do 105 i=1,5
          m=m+1
          go to (51,52,53,54,55,56,57,58,59),m
c-----------------------------------------------------
 59       p=0.25/a**2*(1.+1./a**2)
          q=0.
          r=-0.25
          go to 50
c-----------------------------------------------------
 58       p=(0.333333/a**2-0.666667)/a
          q=0.666667
          r=0.
          go to 50
c-----------------------------------------------------
 57       p=0.5/a**2
          q=0.
          r=-0.5
          go to 50
c-----------------------------------------------------
 56       p=1./a
          q=-1.
          r=0.
          go to 50
c-----------------------------------------------------
 55       p=0.
          q=0.
          r=0.5
          go to 50
c-----------------------------------------------------
 54       p=0.
          q=0.5
          r=0.
          go to 50
c-----------------------------------------------------
 53       p=0.5
          q=0.
          r=0.
          go to 50
c-----------------------------------------------------
 52       p=0.5*a
          q=0.25
          r=0.
          go to 50
c-----------------------------------------------------
 51       p=0.5*a*a+0.5
          q=0.
          r=0.
          go to 50
c-----------------------------------------------------
   50     b=aa*bm(i)
          pp=pp+b*p
          qq=qq+q*b
          rr=rr+r*b
  105 aa=aa*al
      c=exp(-a*a)*pp+spi*erfc(a)*qq+s13aae(a*a,ifl)*rr
      expinv=expinv+c
      if(l) return
c
      c=0.
      d=0.5*(a-1.)
      dd=0.5*(a+1.)
      do 106 i=1,8
          x=xm(i)
          x1=xx(x)
          x2=xx(-x)
          c=c+(ff(x1)+ff(x2))*cm(i)
  106 continue
      expinv=expinv+c*d
c=====================================================
      end
