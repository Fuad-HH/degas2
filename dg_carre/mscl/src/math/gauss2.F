      function gauss2(f,a,b,eps)
c
c  version : 87/04/08
c
c=====================================================
      real w(12),x(12)
      data const / 1.e-7 /
      data  w /
     1   0.10122 85362, 0.22238 10345, 0.31370 66459, 0.36268 37833,
     2   0.027152 45941,0.062253 52394,0.095158 51168,0.12462 89713,
     3   0.14959 59888, 0.16915 65193, 0.18260 34150, 0.18945 06104/
      data  x /
     1   0.96028 98565, 0.79666 64774, 0.52553 24099, 0.18343 46425,
     2   0.98940 09350, 0.94457 50231, 0.86563 12024, 0.75540 44084,
     3   0.61787 62444, 0.45801 67777, 0.28160 35508, 0.095012 50984/
c=====================================================
c
      delta=const*abs(a-b)
      gauss2=0.
      aa=a
  5   y=b-aa
      if(abs(y).lt.delta) return
c=====================================================
  2   bb=aa+y
      c1=0.5*(aa+bb)
      c2=c1-aa
      s8=0.
      s16=0.
      do 100 i=1,4
      u=x(i)*c2
 100  s8=s8+w(i)*(f(c1+u)+f(c1-u))
      do 101 i=5,12
      u=x(i)*c2
 101  s16=s16+w(i)*(f(c1+u)+f(c1-u))
      s8=s8*c2
      s16=s16*c2
      if(abs(s16-s8).gt.eps*(1.+abs(s16))) go to 4
      gauss2=gauss2+s16
      aa=bb
      go to 5
  4   y=0.5*y
      if(abs(y).gt.delta) go to 2
      print 700
  700 format(' gauss2....too high accuracy required')
      gauss2=0.
c=====================================================
      end
