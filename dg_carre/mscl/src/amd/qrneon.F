      function qrneon(t,p)
c
c  version : 31.05.91 18:41
c
c=====================================================
c*** neon radiation in presense of neutral hydrogen
c***           (approximate formula)
c*** input:
c***  t  - electron temperature, ev
c***  p  - ratio of neutral hydrogen density to electron one
c*** output:
c***     rate constant, 10**26 cm**3 10**19 ev/sec
c=====================================================
c
      parameter (nv=2, nc=3, nn=12, nnc=nn*nc)
      dimension kbm(nv),lbm(nv),nm(nv),ff(10),f(10),
     ,                          xm(nn),cm(nnc),dm(nnc),prm(nv)
c
      data kbm / 1,9 /
      data lbm / 1,9 /
      data nm / 8,4 /
      data xm /
     *         4.00e+00, 3.00e+01, 5.00e+01, 7.00e+01,
     *         9.00e+01, 1.10e+02, 1.30e+02, 1.80e+02,
     *         1.00e-05, 4.00e-04, 8.00e-04, 3.00e-03  /
      data cm /
     *         1.12e-02, 2.87e+00, 3.51e+00, 3.09e+00,
     *         2.59e+00, 2.22e+00, 1.97e+00, 1.60e+00,
     *         9.93e-01, 1.98e+00, 2.40e+00, 3.20e+00,
     *         8.13e-03, 1.95e+00, 1.39e+00,-3.57e-01,
     *        -9.79e-01,-1.18e+00,-1.21e+00,-1.16e+00,
     *         1.79e+00, 9.40e-01, 2.68e-01,-1.34e+00,
     *        -3.61e-03,-7.10e-01, 2.81e-01, 9.12e-01,
     *         2.68e-01,-2.23e-01,-4.40e-01,-6.84e-01,
     *        -9.09e-01, 6.60e-01, 6.57e-01,-6.19e-01  /
      data dm /
     *         1.30e-01, 7.13e-02,-2.53e-03,-2.85e-02,
     *        -2.18e-02,-1.51e-02,-1.01e-02,-6.16e-03,
     *         2.89e+03, 1.81e+03, 6.30e+02, 2.30e+02,
     *         9.98e-02, 2.47e-02,-7.61e-02,-6.66e-02,
     *        -1.27e-02,-5.47e-03, 6.70e-04, 1.18e-03,
     *        -2.28e+03,-1.96e+03,-1.44e+03,-3.74e+02,
     *        -5.02e-02, 1.90e-02, 5.74e-02,-5.50e-03,
     *        -3.74e-02,-1.53e-02,-7.76e-03,-3.43e-03,
     *         5.03e+03, 2.02e+03,-9.66e+02,-3.87e+02  /
c=====================================================
c
      prm(1)=t
      prm(2)=p
      call vfill(f,nc,1.)
c-----------------------------------------------------
      do 1100 i=1,nv
      n=nm(i)
      if(n.eq.0) go to 1100
c-----------------------------------------------------
      kb=kbm(i)
      lb=lbm(i)
      kf=kb+n-1
      w=prm(i)
      if(w.ge.xm(kb)) go to 120
c-----------------------------------------------------
      go to (30,40),i
c-----------------------------------------------------
c*** x < xmin
c
 30   call vzero(ff,nc)
      go to 400
 40   do 1001 k=1,nc
      ff(k)=cm(lb)
 1001 lb=lb+nn
      go to 400
c-----------------------------------------------------
 120  if(w.le.xm(kf)) go to 300
c-----------------------------------------------------
c*** x > xmax
c
      go to (300,160),i
c-----------------------------------------------------
 160  lf=nn
      do 1020 k=1,nc
         ff(k)=cm(lf)
 1020 lf=lf+nn
      go to 400
c-----------------------------------------------------
 300  call splinv(w,xm(kb),cm(lb),dm(lb),ff,n,nn,nc,1,ir)
 400  do 1050 l=1,nc
      f(l)=f(l)*ff(l)
 1050 continue
c-----------------------------------------------------
 1100 continue
c-----------------------------------------------------
      w=0.
      do 1200 i=1,nc
      w=w+f(i)
 1200 continue
c-----------------------------------------------------
      qrneon=0.625*amax1(w,0.)
c=====================================================
      end
