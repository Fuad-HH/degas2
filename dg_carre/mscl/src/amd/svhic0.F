      function svhic0(t)
c
c  version : 88/07/28
c
      parameter (n=6,m=3)
      real am(n),bm(m)
      data  am / 5.9848, 1.1903,-3.0140,-1.3693, .83748, .40150 /,
     ,                     bm          ,   al ,   ui  /
     /          -65.826, 205.21,-446.94, 37.442, 11.3 /
c=====================================================
c
      svhic0 = 0.
      x = t/ui
      v = 1.
      w = 0.
      if(x.gt.10.) go to 10
c-----------------------------------------------------
      if(x.lt.0.01) return
c=====================================================
      y = alog10(x)
      do 100 i = 1,n
      w = w+am(i)*v
 100  v = v*y
      svhic0 = exp(-1./x)*(sqrt(x)*w)
      return
c=====================================================
 10   do 110 i=1,m
      w = w+bm(i)/v
 110  v = v*x
      svhic0 = (al*alog(x)+w)/sqrt(x)
c=====================================================
      end
