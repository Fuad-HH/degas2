      function svhihe(t)
c
c  version : 88/07/28
c
      parameter (n=6,m=3)
      real am(n),bm(m)
      data  am / 1.4999,.056656,-.60821,-.35894, .15529, .13207 /,
     ,                     bm          ,   al  ,    ui  /
     /           4.7893,-77.359, 373.66, 3.1373,   24.6 /
c=====================================================
c
      svhihe = 0.
      x = t/ui
      v = 1.
      w = 0.
      if(x.gt.10.) go to 10
c-----------------------------------------------------
      if(x.lt.0.01) return
c=====================================================
      y = alog10(x)
      do 100 i = 1,n
      w = w+am(i)*v
 100  v = v*y
      svhihe = exp(-1./x)*(sqrt(x)*w)
      return
c=====================================================
 10   do 110 i=1,m
      w = w+bm(i)/v
 110  v = v*x
      svhihe = (al*alog(x)+w)/sqrt(x)
c=====================================================
      end
