      function svhih(t)
c
c  version : 88/07/28
c
      parameter (n=6,m=3)
      real am(n),bm(m)
      data  am / 2.3742,-.36866,-1.0366,-.38010, .34159, .16834 /,
     ,                     bm          ,   al ,   ui  /
     /           9.5986,-92.463, 399.73, 2.4617, 13.6 /
c=====================================================
c
      svhih = 0.
      x = t/ui
      v = 1.
      w = 0.
      if(x.gt.10.) go to 10
c-----------------------------------------------------
      if(x.lt.0.01) return
c=====================================================
      y = alog10(x)
      do 100 i = 1,n
      w = w+am(i)*v
 100  v = v*y
      svhih = exp(-1./x)*(sqrt(x)*w)
      return
c=====================================================
 10   do 110 i=1,m
      w = w+bm(i)/v
 110  v = v*x
      svhih = (al*alog(x)+w)/sqrt(x)
c=====================================================
      end
