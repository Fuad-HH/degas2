C
C     COMMON BLOCK FOR ALADDIN INTERACTIVE PROGRAM
C
C     ORIGINAL STRUCTURE DEFINED BY  R. A. HULSE, PRINCETON UNIVERSITY,
C     PLASMA PHYSICS LABORATORY.
C     (PAPER TO BE SUBMITTED TO THE JOURNAL OF COMPUTATIONAL PHYSICS)
C
C-------------------------------------------------------------------------------
C
C     REV: 2/02/89 BY J.J. SMITH IAEA ATOMIC AND MOLECULAR DATA UNIT
C          ALL LABEL LENGTHS INCREASED FROM 20 CHARACTERS TO 40
C          THE COEFFICIENT ARRAY CF IS DEFINED IN DOUBLE PRECISION
C          THE FLAG FEXN HAS BEEN ADDED TO COMUNICATE WHETHER
C          COEFFICIENTS CAN BE PRINTED IN 1PE13.6 FORMAT
C
C-------------------------------------------------------------------------------
C
C     NOTE: CHARACTER VARIABLES ARE IN A SEPARATE COMMON BLOCK TO ACCOMODATE
C           FORTRAN COMPILERS WHICH REQUIRE THIS SEPARATION OF VARIABLE TYPES
C
C     NSLMX   DIMENSIONED MAXIMUM NUMBER OF SEARCH LABELS
C     NCFMX   DIMENSIONED MAXIMUM NUMBER OF COEFFICIENTS
C
C     LUTIN   LOGICAL UNIT FOR TERMINAL INPUT
C     LUTOUT  LOGICAL UNIT FOR TERMINAL OUTPUT
C     LUDF    LOGICAL UNIT FOR INPUT DATA FILE
C     DFNAME  NAME OF INPUT DATA FILE
C     LUOF    LOGICAL UNIT FOR OUTPUT DATA FILE
C     OFNAME  NAME OF OUTPUT DATA FILE
C     LUQF    LOGICAL UNIT FOR QUERY FILE
C     QFNAME  NAME OF QUERY FILE
C     LUEF    LOGICAL UNIT FOR EVALUATED DATA OUTPUT FILE
C     EFNAME  NAME OF EVALUATED DATA OUTPUT FILE
C     CMND    INPUT COMMAND LINE
C     LABEL   BUFFER ARRAY FOR LABELS
C     NCHLBL  NUMBER OF CHARACTERS IN LABEL
C     HSL     HIERARCHICAL SEARCH LABELS
C     BASL    BOOLEAN .AND. SEARCH LABELS
C     BNSL    BOOLEAN .NOT. SEARCH LABELS
C     NHSL    NUMBER OF HIERARCHICAL SEARCH LABELS
C     NBASL   NUMBER OF BOOLEAN .AND. SEARCH LABELS
C     NBNSL   NUMBER OF BOOLEAN .NOT. SEARCH LABELS
C     CF      COEFFICIENTS CONVERTED TO REAL NUMBERS
C     NCF     NUMBER OF COEFFICIENTS
C     OK      GENERAL PURPOSE STATUS FLAG
C     EOF     .TRUE. IF END OF FILE
C     MATCH   .TRUE./.FALSE. RETURN FROM SEARCH LABEL COMPARISON
C     ERRMSG  ERROR MESSAGE STRING RETURNED FROM VARIOUS SUBROUTINES
C
C------------------------------------------------------------------------------
C
      PARAMETER (NSLMX=100, NCFMX=200)
C
      CHARACTER*80 DFNAME, OFNAME, QFNAME, EFNAME, CMND, ERRMSG
      CHARACTER*40 LABEL, HSL(NSLMX), BASL(NSLMX), BNSL(NSLMX)
      LOGICAL OK, EOF, MATCH
C
      DOUBLE PRECISION CF(NCFMX)
C
      COMMON / ALCOM  / LUTIN, LUTOUT, LUDF, LUOF, LUQF, LUEF,
     &                  NCHLBL, NHSL, NBASL, NBNSL, CF, NCF,
     &                  OK, EOF, MATCH
C
      COMMON / ALCOML / DFNAME, OFNAME, QFNAME, EFNAME, CMND, ERRMSG,
     &                  LABEL, HSL, BASL, BNSL
C
C------------------------------------------------------------------------------
C
