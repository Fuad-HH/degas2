C
C     COMMON BLOCK FOR ALPACK STANDARD ALADDIN ENTRY PARSING
C
C     ORIGINAL STRUCTURE DEFINED BY  R. A. HULSE, PRINCETON UNIVERSITY,
C     PLASMA PHYSICS LABORATORY.
C     (PAPER TO BE SUBMITTED TO THE JOURNAL OF COMPUTATIONAL PHYSICS)
C
C-------------------------------------------------------------------------------
C
C     REV: 2/02/89 BY J.J. SMITH IAEA ATOMIC AND MOLECULAR DATA UNIT
C          ALL LABEL LENGTHS INCREASED FROM 20 CHARACTERS TO 40
C          THE FLAG FEXN HAS BEEN ADDED TO COMUNICATE WHETHER
C          COEFFICIENTS CAN BE PRINTED IN 1PE13.6 FORMAT
C
C------------------------------------------------------------------------------
C
C     NOTE: CHARACTER VARIABLES ARE IN A SEPARATE COMMON BLOCK TO ACCOMODATE
C           FORTRAN COMPILERS WHICH REQUIRE THIS SEPARATION OF VARIABLE TYPES
C
C     NELMX   DIMENSIONED MAXIMUM NUMBER OF LINES IN ENTRY BUFFER
C     NHLMX   DIMENSIONED MAXIMUM NUMBER OF HIERARCHICAL LABELS
C     NBLMX   DIMENSIONED MAXIMUM NUMBER OF BOOLEAN LABELS
C
C     LESEQN  ENTRY SEQUENCE NUMBER (0 = NO ENTRY CURRENTLY IN BUFFER)
C     EBUFF   BUFFER FOR CURRENT ENTRY LINES, PLUS FIRST LINE OF NEXT ENTRY
C     NELN    NUMBER OF LINES IN THIS ENTRY
C     HL      HIERARCHICAL LABELS
C     BL      BOOLEAN LABELS
C     NHL     NUMBER OF HIERARCHICAL LABELS
C     NBL     NUMBER OF BOOLEAN LABELS
C     LCMPTR  POINTER TO FIRST COMMENT LINE IN EBUFF
C     NCMLN   NUMBER OF COMMENT LINES IN EBUFF
C     LCFPTR  POINTER TO FIRST LINE OF COEFFICIENT FIELD IN EBUFF
C     NCFLN   NUMBER OF COEFFICIENT FIELD LINES
C
C     FEXTN   .FALSE. IF COEFFICIENTS CANNOT BE PRINTED IN 1PE13.6
C              FORMAT
C
C------------------------------------------------------------------------------
C
      PARAMETER (NELNMX=100, NHLMX=100, NBLMX=100)
C
      CHARACTER*80 EBUFF(NELNMX)
      CHARACTER*40 HL(NHLMX), BL(NBLMX)
      LOGICAL FEXTN
C
      COMMON / ALENT  / LESEQN, NELN, NHL, NBL,
     &                  LCMPTR, NCMLN, LCFPTR, NCFLN,
     &                  FEXTN
C
      COMMON / ALENTL / EBUFF, HL, BL
C
